import { writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = path.join(root, "src/lib/githubStats.ts");

// Accounts whose public work counts toward the site's "public repositories"
// and "live in production" mini metrics. Add/remove accounts here.
const ACCOUNTS = [
  { type: "users", name: "Dposleman" },
  { type: "orgs", name: "UnderStack-Dk" },
];

async function fetchRepos({ type, name }) {
  const repos = [];
  let page = 1;
  for (;;) {
    const response = await fetch(`https://api.github.com/${type}/${name}/repos?per_page=100&page=${page}`, {
      headers: { Accept: "application/vnd.github+json", "User-Agent": "understack-site-build" },
    });
    if (!response.ok) {
      throw new Error(`GitHub API error for ${type}/${name}: ${response.status} ${response.statusText}`);
    }
    const data = await response.json();
    repos.push(...data);
    if (data.length < 100) break;
    page += 1;
  }
  return repos;
}

// Forks aren't this account's own work, and dotfile repos (".github", etc.)
// are GitHub-internal config repos, not real projects.
function isRealProject(repo) {
  return !repo.fork && !repo.name.startsWith(".");
}

// "Live in production" is a repo whose GitHub "Website" field is filled in.
// This only counts what GitHub actually knows about — if a real live
// product's repo doesn't have that field set, it won't be counted here.
function isLiveInProduction(repo) {
  return Boolean(repo.homepage && repo.homepage.trim().length > 0);
}

async function main() {
  const projects = [];
  for (const account of ACCOUNTS) {
    const repos = await fetchRepos(account);
    projects.push(...repos.filter(isRealProject));
  }

  const publicRepos = projects.length;
  const liveInProduction = projects.filter(isLiveInProduction).length;

  const content = `// Auto-generated by scripts/fetch-github-stats.mjs during \`npm run build\`.
// Do not edit by hand — this file is overwritten on every build with fresh
// counts from the GitHub API. If GitHub was unreachable at build time, the
// previously committed values below are kept as-is.
export const githubStats = {
  publicRepos: ${publicRepos},
  liveInProduction: ${liveInProduction},
  updatedAt: "${new Date().toISOString().slice(0, 10)}",
};
`;

  await writeFile(outputPath, content, "utf8");
  console.log(`GitHub stats updated: ${publicRepos} public repos, ${liveInProduction} live in production.`);
}

main().catch((error) => {
  console.warn(`Skipping GitHub stats refresh (${error.message}).`);
  console.warn("Keeping the previously committed src/lib/githubStats.ts values.");
});
